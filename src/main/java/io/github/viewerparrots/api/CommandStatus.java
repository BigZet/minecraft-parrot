package io.github.viewerparrots.api;

/**
 * Статусы результата команды (раздел 6.2 ТЗ).
 *
 * <p>Пока Future не завершён, команда находится в {@code ACCEPTED} и уже имеет commandId.
 * Brigadier возвращает 1 при приёме и 0 при синхронном отказе — это не обещание
 * завершённой записи на диск.
 */
public enum CommandStatus {
	/** Принята к исполнению; итог придёт позже отдельным сообщением. */
	ACCEPTED,
	SUCCEEDED,
	/** Отвергнута до начала работы: права, аргументы, состояние, лимиты. */
	REJECTED,
	/** Начата, но не выполнена: ошибка I/O или рантайма. */
	FAILED,
	/** Замещена другим действием или отменена событием жизненного цикла. */
	CANCELLED;

	public boolean isTerminal() {
		return this != ACCEPTED;
	}
}
